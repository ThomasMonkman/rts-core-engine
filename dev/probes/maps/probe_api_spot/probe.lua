local function bpstats()
    local cats = { unit = 0, proj = 0, prop = 0, mesh = 0, emit = 0, beam = 0, trail = 0, otherbp = 0, other = 0, num = 0 }
    local samples = { otherbp = {}, other = {}, emit = {}, mesh = {}, prop = {}, beam = {}, trail = {}, proj = {} }
    for k, v in __blueprints do
        local c
        if type(k) ~= 'string' then c = 'num'
        elseif not string.find(k, '/', 1, true) then c = 'unit'
        elseif string.find(k, '_proj%.bp$') then c = 'proj'
        elseif string.find(k, '_prop%.bp$') then c = 'prop'
        elseif string.find(k, '_mesh') then c = 'mesh'
        elseif string.find(k, '_emit%.bp$') or string.find(k, '/emitters/') then c = 'emit'
        elseif string.find(k, '_beam%.bp$') or string.find(k, '/beams/') then c = 'beam'
        elseif string.find(k, '_trail%.bp$') or string.find(k, '/trails/') then c = 'trail'
        elseif string.find(k, '%.bp$') then c = 'otherbp'
        else c = 'other' end
        cats[c] = cats[c] + 1
        if samples[c] then table.insert(samples[c], k) end
    end
    local s = ''
    for _, c in { 'unit', 'proj', 'prop', 'mesh', 'emit', 'beam', 'trail', 'otherbp', 'other', 'num' } do s = s .. ' ' .. c .. '=' .. cats[c] end
    LOG('PROBE ' .. LAYER .. ' bpstats' .. s)
    for c, list in samples do
        table.sort(list)
        local n = table.getn(list)
        local out = ''
        local step = math.max(1, math.floor(n / 4))
        local i = 1
        local shown = 0
        while i <= n and shown < 5 do out = out .. ' ' .. list[i] i = i + step shown = shown + 1 end
        LOG('PROBE ' .. LAYER .. ' bpsample ' .. c .. out)
    end
    local up, low, mixed, other = 0, 0, 0, 0
    local lows, mixeds = {}, {}
    for k, v in categories do
        if type(k) ~= 'string' then other = other + 1
        elseif string.upper(k) == k then up = up + 1
        elseif string.lower(k) == k then low = low + 1 table.insert(lows, k)
        else mixed = mixed + 1 table.insert(mixeds, k) end
    end
    LOG('PROBE ' .. LAYER .. ' catstats upper=' .. up .. ' lower=' .. low .. ' mixed=' .. mixed .. ' other=' .. other)
    table.sort(lows) table.sort(mixeds)
    local n = table.getn(lows)
    local out = ''
    local step = math.max(1, math.floor(n / 12))
    local i = 1
    while i <= n do out = out .. ' ' .. lows[i] i = i + step end
    LOG('PROBE ' .. LAYER .. ' catsample lower' .. out)
    out = ''
    for i = 1, math.min(12, table.getn(mixeds)) do out = out .. ' ' .. mixeds[i] end
    LOG('PROBE ' .. LAYER .. ' catsample mixed' .. out)
end
local function mkeys(t, seen, acc)
    seen = seen or {}; acc = acc or {}
    if type(t) ~= 'table' or seen[t] then return acc end
    seen[t] = true
    for k, v in next, t do
        if type(k) == 'string' and acc[k] == nil then
            local tv = type(v)
            if tv == 'function' and debug and debug.info and debug.info(v, 's') == '[C]' then tv = 'cfunction' end
            acc[k] = tv
        end
    end
    local mt = getmetatable(t)
    if type(mt) == 'table' then
        local ix = rawget(mt, '__index')
        if type(ix) == 'table' and ix ~= _G then mkeys(ix, seen, acc) end
    end
    return acc
end
-- C-function names reachable from a live object (its own fields, then the metatable chain)
local function objdump(tag, obj)
    if obj == nil then LOG('PROBE SIM OBJ.' .. tag .. ' nil') return end
    local mt = getmetatable(obj)
    LOG('PROBE SIM OBJ.' .. tag .. ' type=' .. type(obj) .. ' mt=' .. type(mt) .. ' index=' .. type(mt and rawget(mt, '__index')) .. ' cobj=' .. type(type(obj) == 'table' and rawget(obj, '_c_object') or nil))
    local acc = mkeys(obj)
    local parts = {}
    local nl = 0
    for k, v in acc do
        if v == 'cfunction' then table.insert(parts, k) elseif v == 'function' then nl = nl + 1 end
    end
    LOG('PROBE SIM OBJ.' .. tag .. ' luafns=' .. nl)
    emitlist('OBJ.' .. tag, parts, 14)
end
local function flat(prefix, t, out, d)
    for k, v in t do
        local p = prefix .. tostring(k)
        local tv = type(v)
        if tv == 'table' then
            if next(v) == nil then table.insert(out, p .. '={}')
            elseif d < 5 then flat(p .. '.', v, out, d + 1)
            else table.insert(out, p .. '={..}') end
        elseif tv == 'number' then table.insert(out, p .. '=' .. num(v))
        elseif tv == 'string' then table.insert(out, p .. '=' .. (string.gsub(string.sub(v, 1, 48), '[%s%c]', '_')))
        elseif tv == 'boolean' then table.insert(out, p .. '=' .. tostring(v))
        else table.insert(out, p .. '=<' .. (tv == 'cfunction' and 'function' or tv) .. '>') end
    end
end
