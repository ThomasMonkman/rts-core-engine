local LAYER = 'UI' -- API spot-check probe (interface half); first line is code so --ui-lua accepts it
local function num(v)
    if v ~= v then return 'nan' end
    if v == 1 / 0 then return 'inf' end
    if v == -1 / 0 then return '-inf' end
    if v == math.floor(v) and v > -1e9 and v < 1e9 then return string.format('%d', v) end
    return string.format('%.3f', v)
end
local function clean(s)
    return (string.gsub(string.sub(s, 1, 110), '[%c]', '~'))
end
local function ser(v, d)
    d = d or 0
    local t = type(v)
    if t == 'number' then return num(v)
    elseif t == 'string' then return '"' .. clean(v) .. '"'
    elseif t == 'nil' or t == 'boolean' then return tostring(v)
    elseif t == 'table' then
        if d >= 2 then return '{..}' end
        local ks = {}
        for k in v do table.insert(ks, k) end
        table.sort(ks, function(a, b)
            local ta, tb = type(a), type(b)
            if ta ~= tb then return ta < tb end
            if ta == 'number' or ta == 'string' then return a < b end
            return tostring(a) < tostring(b)
        end)
        local s = '{'
        local n = 0
        for _, k in ks do
            n = n + 1
            if n > 14 then s = s .. '+' .. (table.getn(ks) - 14) .. 'more' break end
            s = s .. (type(k) == 'string' and k or ('[' .. tostring(k) .. ']')) .. '=' .. ser(v[k], d + 1) .. ' '
        end
        return s .. '}'
    elseif t == 'cfunction' then return 'function'
    else return t end
end
-- a wait every ten cases: the log gets written out, so a case that takes the game down is easy to find
local tcount = 0
local function T(label, fn)
    local ok, a, b, c, d = pcall(fn)
    local s
    if ok then
        local vals = { a, b, c, d }
        local n = 4
        while n > 0 and vals[n] == nil do n = n - 1 end
        s = 'ok'
        for i = 1, n do s = s .. ' ' .. ser(vals[i]) end
    else
        s = 'ERR ' .. clean(tostring(a))
    end
    LOG('PROBE ' .. LAYER .. ' ' .. label .. ' => ' .. s)
    tcount = tcount + 1
    if math.mod(tcount, 10) == 0 then WaitSeconds(0.05) end
end
local function keysof(t)
    if type(t) ~= 'table' then return type(t) end
    local ks = {}
    for k, v in t do table.insert(ks, tostring(k) .. ':' .. (type(v) == 'cfunction' and 'function' or type(v))) end
    table.sort(ks)
    return table.concat(ks, ' ')
end
local function emitlist(tag, parts, per)
    table.sort(parts)
    local n = table.getn(parts)
    LOG('PROBE ' .. LAYER .. ' ' .. tag .. ' #' .. n)
    local i = 1
    while i <= n do
        local j = math.min(i + per - 1, n)
        local s = ''
        for x = i, j do s = s .. ' ' .. parts[x] end
        LOG('PROBE ' .. LAYER .. ' ' .. tag .. ' =' .. s)
        i = j + 1
    end
end
