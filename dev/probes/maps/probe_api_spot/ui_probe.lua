-- selection-dependent cases: run once the sim half's units exist
local function uiunit()
    UISelectionByCategory('ALLUNITS', false, false, false, false)
    local sel = GetSelectedUnits()
    T('uu.sel_immediate', function() return type(sel), sel and table.getn(sel) > 0 end)
    WaitSeconds(0.5)
    sel = GetSelectedUnits()
    T('uu.sel', function() return type(sel), sel and table.getn(sel) > 0 end)
    local u
    for _, x in sel or {} do if x:GetUnitId() == 'uel0201' then u = x end end
    if not u then LOG('PROBE UI uu.none') return end
    T('uu.type', function() return type(u), type(getmetatable(u)), type(rawget(u, '_c_object')) end)
    T('uu.id', function() return type(u:GetEntityId()), u:GetUnitId(), u:GetArmy(), u:GetBlueprint() == __blueprints.uel0201 end)
    T('uu.health', function() return type(u:GetHealth()), u:GetMaxHealth(), u:GetFuelRatio(), u:GetShieldRatio() end)
    T('uu.work', function() return u:GetWorkProgress(), u:GetBuildRate(), u:IsIdle(), u:IsDead() end)
    T('uu.flags', function() return u:IsStunned(), u:IsAutoMode(), u:IsRepeatQueue(), u:IsOverchargePaused() end)
    T('uu.flags2', function() return u:HasUnloadCommandQueuedUp(), u:IsInCategory('LAND'), u:IsInCategory('AIR'), u:IsInCategory('NOSUCHCAT') end)
    T('uu.incat_noarg', function() return u:IsInCategory() end)
    T('uu.incat_cat', function() return u:IsInCategory(categories.LAND) end)
    T('uu.econ', function() return keysof(u:GetEconData()) end)
    T('uu.missile', function() return keysof(u:GetMissileInfo()) end)
    T('uu.cmdq', function() local q = u:GetCommandQueue() return type(q), q and table.getn(q) end)
    T('uu.stat', function() return u:GetStat('NOSUCHSTAT'), u:GetStat('NOSUCHSTAT', 3) end)
    T('uu.stat2', function() return keysof(u:GetStat('KILLS', 0)) end)
    T('uu.sets', function() return u:GetSelectionSets(), u:HasSelectionSet('x') end)
    T('uu.sets2', function() u:AddSelectionSet('probe') local a = u:HasSelectionSet('probe') local s = u:GetSelectionSets() u:RemoveSelectionSet('probe') return a, s, u:HasSelectionSet('probe') end)
    T('uu.footprint', function() return u:GetFootPrintSize() end)
    T('uu.pos', function() local p = u:GetPosition() return type(p), table.getn(p), getmetatable(p) == getmetatable(Vector(0, 0, 0)) end)
    T('uu.ipos', function() return type(u.GetInterpolatedPosition), type(u.GetInterpolatedPosition and u:GetInterpolatedPosition()) end)
    T('uu.name', function() return u:GetCustomName(u), u:GetCustomName() end)
    T('uu.setname', function() u:SetCustomName('probe') return u:GetCustomName(u) end)
    T('uu.rel', function() return u:GetFocus(), u:GetGuardedEntity(), u:GetCreator() end)
    T('uu.cansee', function() return u:CanAttackTarget(u, false) end)
    T('uu.badself', function() return u.GetHealth({}) end)
    T('uu.cmddata', function() return keysof(GetUnitCommandData({ u })) end)
    T('uu.cmddata2', function() local a, b, c, d = GetUnitCommandData({ u }) return type(a), type(b), type(c), type(d) end)
    T('uu.cmddata3', function() local a, b, c, d = GetUnitCommandData({ u }) return keysof(a) end)
    T('uu.cmddata4', function() local a, b, c, d = GetUnitCommandData({ u }) return keysof(b) end)
    T('uu.cmddata5', function() local a, b, c, d = GetUnitCommandData({ u }) return keysof(c) end)
    T('uu.rollover', function() return GetRolloverInfo() end)
    T('uu.firestate', function() return GetFireState({ u }) end)
    T('uu.scriptbit', function() return GetScriptBit({ u }, 0), GetScriptBit({ u }, 4) end)
    T('uu.validate', function() return ValidateUnitsList and table.getn(ValidateUnitsList({ u })) end)
    T('uu.attached', function() return GetAttachedUnitsList({ u }) end)
    T('uu.isbp', function() return type(GetUnitById(u:GetEntityId())), GetUnitById(u:GetEntityId()) == u, GetUnitById('nosuch') end)
    T('uu.catfilter', function() return table.getn(EntityCategoryFilterDown(categories.LAND, { u })), table.getn(EntityCategoryFilterDown(categories.AIR, { u })) end)
    T('uu.catfilterout', function() return table.getn(EntityCategoryFilterOut(categories.LAND, { u })) end)
    T('uu.catcontains', function() return EntityCategoryContains(categories.LAND, u) end)
    T('uu.selected', function() SelectUnits({ u }) return table.getn(GetSelectedUnits()), GetSelectedUnits()[1] == u end)
    T('uu.selected_clear', function() SelectUnits(nil) return GetSelectedUnits() end)
    local acc = {}
    local mt = getmetatable(u)
    local seen = {}
    local function walk(t)
        if type(t) ~= 'table' or seen[t] then return end
        seen[t] = true
        for k, v in next, t do
            local tv = type(v)
            if tv == 'function' and debug and debug.info and debug.info(v, 's') == '[C]' then tv = 'cfunction' end
            if type(k) == 'string' and tv == 'cfunction' and acc[k] == nil then acc[k] = true end
        end
        local m = getmetatable(t)
        if type(m) == 'table' then walk(rawget(m, '__index')) end
    end
    walk(u)
    local parts = {}
    for k in acc do table.insert(parts, k) end
    emitlist('OBJ.userunit', parts, 14)
end
